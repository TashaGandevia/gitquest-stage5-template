#!/usr/bin/env node
// Regenerates .github/screenshots/README.md: how screenshots work, and a
// reference table of every image the task issues use. Run it after adding,
// renaming or removing a shot(...) call in scripts/lib/missions.mjs.
//
//   node scripts/list-screenshots.mjs

import { writeFileSync } from 'node:fs';
import { SCREENSHOT_LIST, STEPS } from './lib/missions.mjs';

// Building every step's text records each shot(...) it uses.
for (const key of Object.keys(STEPS)) STEPS[key]({ self: 1, link: 2, handoverPr: 3, discrepancy: 4, reviewPr: 5 });

const rows = [...SCREENSHOT_LIST]
  .sort(([a], [b]) => a.localeCompare(b, undefined, { numeric: true }))
  .map(([name, description]) => `| \`${name}.png\` | ${description} |`);

writeFileSync(new URL('../.github/screenshots/README.md', import.meta.url), `# Screenshots

Images shown in the task issues (M14.1, M15.2, ...). Station control writes
each issue when the learner reaches that task; every \`[SCREENSHOT]: ...\` line
in it is followed by an image loaded from this folder.

## How they're shown

- In the code, a screenshot is a \`shot('<name>', '<description>')\` call in
  \`scripts/lib/missions.mjs\`, placed where the image belongs in the task.
- In the issue it becomes the \`[SCREENSHOT]: <description>\` line, then the
  image \`.github/screenshots/<name>.png\`.
- The image address points at the **learner's own copy** of the repository
  (\`https://raw.githubusercontent.com/<their repo>/<default branch>/.github/screenshots/<name>.png\`),
  filled in when the issue is created. Their copy is public, so GitHub can
  show it, and the images come with every copy of the template.
- If a file is missing, the issue shows a broken image under its line.

## Changing them

| To... | Do this |
|---|---|
| Replace an image | Save the new file here with the **same name**. Issues load it fresh, so it also updates issues that already exist in a learner's copy once their copy has the file |
| Add a screenshot | Add a \`shot('<name>', '<description>')\` call in \`scripts/lib/missions.mjs\`, save \`<name>.png\` here, then run \`node scripts/list-screenshots.mjs\` |
| Rename or remove one | Change or delete the \`shot(...)\` call and the file, then run \`node scripts/list-screenshots.mjs\` |
| Change the description | Edit the second argument of the \`shot(...)\` call. Issues already created keep the old wording |

**Names:** \`m<mission>-<task>-<a few words>\`, lowercase with dashes, e.g.
\`m14-1-issue-sidebar-assignees-open\`. PNG, roughly 1200 to 1600 pixels wide;
crop to the part of the screen the task is about.

## Images in use

This table is regenerated by \`node scripts/list-screenshots.mjs\`.

| File | What it shows |
|---|---|
${rows.join('\n')}
`);
console.log(`Wrote .github/screenshots/README.md (${rows.length} screenshots)`);
